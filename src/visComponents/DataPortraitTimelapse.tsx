export enum WhichPortraitTimelapse {
    Jess = "Jess",
    Val = "Val",
    ValFootage = "Val Footage",
    Robin = "Robin",
    Eggplant = "Eggplant",
    Baklava = "Baklava"
}

const DataPortraitTimelapse = ({ whichPortrait }: { whichPortrait: WhichPortraitTimelapse }) => {

    let [frameIndex, setFrameIndex] = useState<number>(0);

    let useFrames: any[];
    let useCaptionText;
    if (whichPortrait === WhichPortraitTimelapse.Val) {
        useFrames = valDrummingFrames;
        useCaptionText = "Excerpt of Portrait of Val Drumming (2022)";

    } else if (whichPortrait === WhichPortraitTimelapse.ValFootage) {
        useFrames = valFootageFrames;
        useCaptionText = "Movement data collected via motion capture";

    } else if (whichPortrait === WhichPortraitTimelapse.Jess) {
        useFrames = jessPortraitFrames;
        useCaptionText = "Excerpt of Portrait of Jess Dancing Burlesque (2022)";

    } else if (whichPortrait === WhichPortraitTimelapse.Robin) {
        useFrames = robinPortraitFrames;
        useCaptionText = "Excerpt of Portrait of Robin Conducting Traffic (2022)";

    } else if (whichPortrait === WhichPortraitTimelapse.Eggplant) {
        useFrames = eggplantPortraitFrames;
        useCaptionText = "Excerpt of Portrait of Abdul Picking Eggplants (2022)";

    } else if (whichPortrait === WhichPortraitTimelapse.Baklava) {
        useFrames = baklavaPortraitFrames;
        useCaptionText = "Excerpt of Portrait of Basma Making Baklava (2022)";

    } else {
        useFrames = [];
    }

    let useStyle = {};
    if (whichPortrait === WhichPortraitTimelapse.ValFootage) {
        /* This is a custom-calculated aspect ratio for Val drumming footage images */
        useStyle = { aspectRatio: "800 / 563" };

    } else if (whichPortrait === WhichPortraitTimelapse.Baklava) {
        /* This is a custom-calculated aspect ratio for the baklava portrait images */
        useStyle = { aspectRatio: "1024 / 562" };

    }

    useEffect(() => {

        const frameInterval = setInterval(() => {

            setFrameIndex((currentFrameIndex: number) => {

                if (currentFrameIndex < useFrames.length - 1) {

                    return currentFrameIndex + 1;
                } else {
                    return 0;
                }

            });

        }, 400);

        return () => clearInterval(frameInterval);

    }, []);

    let caption;
    if (whichPortrait === WhichPortraitTimelapse.ValFootage) {
        caption = null;
    } else {
        caption = <DataPortraitCaption>
            {useCaptionText}
        </DataPortraitCaption>;
    }

    return <DataPortraitFrameAndCaptionContainer>
        <DataPortraitFrameContainer style={useStyle}>
            {useFrames.map((imageFile: any, index: number) => {

                return <DataPortraitFrame className={index <= frameIndex ? "enter" : "exit"} src={imageFile} key={`dp_frame_${index}`} />

            })}
        </DataPortraitFrameContainer>
        {caption}
    </DataPortraitFrameAndCaptionContainer>;


}

export default DataPortraitTimelapse;